// add function
function add(a, b) {
    return a + b;
}

// subtract function
function subtract(a, b) {
    return a - b;
}

// multiple function
function multiple(a, b) {
    return a * b;
}

// divide fuction
function divide(a, b) {
    return a / b;
}

// test
console.log(add(2, 3));
console.log(subtract(2, 3));
console.log(multiple(2, 3));
console.log(divide(6,3));